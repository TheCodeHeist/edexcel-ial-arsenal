/* Service Worker for Edexcel IAL Arsenal: offline support for the hub, all 10 labs, and visited papers.
   - Hashed /_astro/* bundles & /brand/* icons: cache-first (immutable).
   - HTML navigations & JSON data: network-first with offline cache fallback. */

const CACHE = 'ial-arsenal-v1';
const PRECACHE = ['/', '/chemistry/', '/physics/', '/papers/', '/favicon.svg', '/manifest.webmanifest'];

self.addEventListener('install', (e) => {
  e.waitUntil(
    caches.open(CACHE).then((c) => c.addAll(PRECACHE).catch(() => {})).then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  // Immutable Vite/Astro hashed assets & static brand artwork: cache-first
  if (url.pathname.startsWith('/_astro/') || url.pathname.startsWith('/brand/') || url.pathname === '/favicon.svg') {
    e.respondWith(
      caches.match(req).then((hit) =>
        hit || fetch(req).then((res) => {
          if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
          return res;
        })
      )
    );
    return;
  }

  // Pages & JSON data: network-first, falling back to cache when offline
  e.respondWith(
    fetch(req)
      .then((res) => {
        if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
        return res;
      })
      .catch(() => caches.match(req).then((hit) => hit || (req.mode === 'navigate' ? caches.match('/') : undefined)))
  );
});
